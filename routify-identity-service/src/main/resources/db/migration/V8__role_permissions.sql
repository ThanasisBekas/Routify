-- ============================================================================
-- V8: Role-Permission tables for Granular RBAC (Initiative 04)
-- ============================================================================

-- Role definition table — built-in roles have tenant_id = NULL
CREATE TABLE routify_identity.role_definition (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id   UUID,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    built_in    BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_role_tenant_name UNIQUE (tenant_id, name)
);

-- Permission join table — each row is one permission granted to a role
CREATE TABLE routify_identity.role_permission (
    role_id     UUID NOT NULL REFERENCES routify_identity.role_definition(id) ON DELETE CASCADE,
    permission  VARCHAR(100) NOT NULL,
    PRIMARY KEY (role_id, permission)
);

-- Index for efficient tenant-scoped role queries
CREATE INDEX idx_role_definition_tenant ON routify_identity.role_definition(tenant_id);

